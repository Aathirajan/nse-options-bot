"""
adapters/mapper.py

Maps between INDstocks' several identifier formats and Nautilus's
InstrumentId format, using the instrument master downloaded from
GET /market/instruments (see scripts/refresh_instruments.py) as the
source of truth.

INDstocks uses THREE different identifier shapes for the same
instrument, confirmed against https://api-docs.indstocks.com:

    1. WS subscribe token:   "NSE:2885" or "NFO:51011" (segment token,
                                                                                    used only on the price-feed WebSocket)
  2. REST quotes scrip-code: "NSE_2885" (EXCH_SECURITY_ID, underscore
                                          instead of colon, used by
                                          /market/quotes/*)
  3. REST order security_id: "2885"     (bare SECURITY_ID, exchange is
                                          passed as a separate "exchange"
                                          field in the order payload)

For EQUITY and F&O instruments, all three share the same underlying
SECURITY_ID — this module derives (2) and (3) from (1) plus the
exchange for those types.

**INDEX instruments are the one confirmed exception.** Per the docs'
own explicit warning (Glossary — "Instrument Code Formats"): the WS
feed uses a `NIDX:`/`BIDX:` prefix (not `NSE:`/`BSE:`) for indices, AND
the numeric token itself is NOT guaranteed to match the REST
`security_id` from `/market/instruments?source=index` — the docs give
`NIDX:26000` as their own worked WS example while NIFTY 50's REST
`security_id` is `40000001`; two different numbers. "Do not carry a
token from one to the other — look it up per surface," in the docs'
own words. So for indices, `ws_token` is NOT derived from
`security_id` — it must be set explicitly via `ws_token_override` in
instruments.json (captured from a real WS payload or a known-good
constant), and building an index instrument without one is a stated
gap, not a silent guess.

config/instruments.json is generated by scripts/refresh_instruments.py
from the real CSV; do not hand-maintain it beyond the placeholder rows
used for local testing.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class InstrumentRecord:
    security_id: str          # e.g. "2885" — the join key for EQUITY/F&O;
                               # NOT reliable for INDEX WS tokens, see module docstring
    exchange: str              # "NSE" | "BSE" (from EXCH column)
    nautilus_id: str
    symbol: str
    instrument_type: str       # "EQUITY" | "INDEX" | "OPTION" | "FUTCUR" etc.
    tick_size: float
    lot_size: int
    option_type: str | None = None
    strike: float | None = None
    expiry: str | None = None
    ws_token_override: str | None = None  # required for INDEX, see module docstring

    @property
    def ws_token(self) -> str:
        """
        Format used on the price-feed WebSocket, e.g. 'NSE:2885'.

        For INDEX instruments this does NOT derive from security_id —
        see the module docstring's WARNING. Raises if an index record
        has no ws_token_override set, rather than silently returning a
        token that's likely wrong.
        """
        if self.instrument_type == "INDEX":
            if self.ws_token_override is None:
                raise ValueError(
                    f"'{self.nautilus_id}' is an INDEX instrument with no "
                    f"ws_token_override set — the WS token cannot be derived "
                    f"from its REST security_id (see mapper.py's module "
                    f"docstring). Capture the real WS token (e.g. via "
                    f"scripts/capture_ws_payload.py) and set it in "
                    f"instruments.json."
                )
            return self.ws_token_override
        if self.instrument_type == "OPTION":
            return f"{self.nautilus_id.rsplit('-', 1)[-1]}:{self.security_id}"
        return f"{self.exchange}:{self.security_id}"

    @property
    def rest_scrip_code(self) -> str:
        """Format used by REST /market/quotes/*, e.g. 'NSE_2885'."""
        return f"{self.exchange}_{self.security_id}"


class InstrumentMapper:
    def __init__(self, instrument_master_path: str | Path):
        self._path = Path(instrument_master_path)
        self._by_ws_token: dict[str, InstrumentRecord] = {}
        self._by_security_id: dict[str, InstrumentRecord] = {}
        self._by_nautilus_id: dict[str, InstrumentRecord] = {}
        self.reload()

    def reload(self) -> None:
        with open(self._path) as f:
            data = json.load(f)

        self._by_ws_token.clear()
        self._by_security_id.clear()
        self._by_nautilus_id.clear()

        for row in data.get("instruments", []):
            if row.get("security_id", "").startswith("_") or not row.get("security_id"):
                continue  # skip comment/example rows
            record = InstrumentRecord(
                security_id=row["security_id"],
                exchange=row["exchange"],
                nautilus_id=row["nautilus_id"],
                symbol=row["symbol"],
                instrument_type=row["instrument_type"],
                tick_size=row["tick_size"],
                lot_size=row["lot_size"],
                option_type=row.get("option_type"),
                strike=row.get("strike"),
                expiry=row.get("expiry"),
                ws_token_override=row.get("ws_token_override"),
            )
            try:
                self._by_ws_token[record.ws_token] = record
            except ValueError:
                # INDEX record with no ws_token_override yet — still
                # index it by security_id/nautilus_id below, just skip
                # the WS-token lookup until the token is captured and
                # added. See ws_token's own docstring for why this
                # can't be derived.
                pass
            self._by_security_id[record.security_id] = record
            self._by_nautilus_id[record.nautilus_id] = record

    def to_nautilus_id(self, ws_token: str) -> str:
        record = self._by_ws_token.get(ws_token)
        if record is None:
            raise KeyError(
                f"No mapping for WS token '{ws_token}' — instrument master "
                f"may be stale, run scripts/refresh_instruments.py"
            )
        return record.nautilus_id

    def get_record(self, nautilus_id: str) -> InstrumentRecord:
        record = self._by_nautilus_id.get(nautilus_id)
        if record is None:
            raise KeyError(f"No instrument record for '{nautilus_id}'")
        return record

    def to_ws_token(self, nautilus_id: str) -> str:
        return self.get_record(nautilus_id).ws_token

    def to_security_id(self, nautilus_id: str) -> str:
        return self.get_record(nautilus_id).security_id

    def to_rest_scrip_code(self, nautilus_id: str) -> str:
        return self.get_record(nautilus_id).rest_scrip_code

    def from_ws_token_string(self, ws_token: str) -> InstrumentRecord | None:
        return self._by_ws_token.get(ws_token)

    @staticmethod
    def build_nautilus_id(
        symbol: str,
        expiry: str,  # "2026-08-26"
        strike: float,
        option_type: str,  # "CE" | "PE"
        exchange: str = "NFO",
    ) -> str:
        """
        Construct a Nautilus-style option id from components, e.g.
        NIFTY26AUG24500CE-NFO. This is our own convention, not
        INDstocks' — theirs is a bare SECURITY_ID with no embedded
        meaning, which is exactly why we maintain this mapping layer.
        """
        from datetime import date

        y, m, d = (int(x) for x in expiry.split("-"))
        dt = date(y, m, d)
        month_str = dt.strftime("%b").upper()
        strike_str = str(int(strike)) if strike == int(strike) else str(strike)
        return f"{symbol}{dt.strftime('%y')}{month_str}{strike_str}{option_type}-{exchange}"
